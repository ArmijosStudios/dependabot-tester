"""Files pushed into each generated repo: the package file, an optional lockfile,
`.github/dependabot.yml` and a README."""

import json
import os
import pathlib
import re
import subprocess
import tempfile

from stacks import STACKS


def split_spec(spec):
    """`@scope/pkg@1.0` -> (`@scope/pkg`, `1.0`); `pkg` -> (`pkg`, ``)."""
    idx = spec.rfind("@")
    if idx <= 0:
        return spec.strip(), ""
    return spec[:idx].strip(), spec[idx + 1:].strip()


def python(repo, spec, registry=None):
    m = re.match(r"^\s*([A-Za-z0-9][A-Za-z0-9._-]*)(.*)$", spec)
    name, rest = m.group(1), m.group(2).strip()
    if rest.startswith("@"):
        rest = "==" + rest[1:].strip()
    index = f"--index-url {registry}\n" if registry else ""
    return f"{index}{name}{rest}\n"


def node(repo, spec, registry=None):
    name, version = split_spec(spec)
    return json.dumps({"name": repo, "version": "1.0.0", "private": True,
                       "dependencies": {name: version or "*"}}, indent=2) + "\n"


def ruby(repo, spec, registry=None):
    name, version = split_spec(spec)
    line = f'gem "{name}", "{version}"' if version else f'gem "{name}"'
    return f'source "{registry or "https://rubygems.org"}"\n\n{line}\n'


def go(repo, spec, org="example.com", registry=None):
    name, version = split_spec(spec)
    if not version:
        raise ValueError("Go dependencies need a version, e.g. `github.com/google/uuid@v1.6.0`.")
    return f"module github.com/{org}/{repo}\n\ngo 1.22\n\nrequire {name} {version}\n"


TEMPLATES = {"python": python, "node": node, "ruby": ruby, "go": go}


def package_file(stack, repo, spec, org="example.com", registry=None):
    if stack == "go":
        return go(repo, spec, org, registry)
    return TEMPLATES[stack](repo, spec, registry)


def registry_files(stack, registry):
    """Extra files that point the package manager itself at the registry."""
    if stack == "node" and registry:
        return {".npmrc": f"registry={registry}/\n"}
    return {}


# Dependabot only accepts insecure-external-code-execution for these ecosystems.
CODE_EXECUTION_ECOSYSTEMS = {"bundler", "mix", "pip"}


def dependabot_yml(stack, registry=None):
    eco = STACKS[stack]["ecosystem"]
    code_exec = "    insecure-external-code-execution: allow\n" if eco in CODE_EXECUTION_ECOSYSTEMS else ""
    registries, use = "", ""
    if registry:
        # goproxy-server has no replaces-base; Dependabot uses the configured proxy directly.
        base = "" if stack == "go" else "    replaces-base: true\n"
        registries = (f"registries:\n  {stack}:\n    type: {STACKS[stack]['registry_type']}\n"
                      f'    url: "{registry}"\n{base}')
        use = f"    registries:\n      - {stack}\n"
    return (
        "version: 2\n"
        f"{registries}"
        "updates:\n"
        f'  - package-ecosystem: "{eco}"\n'
        '    directory: "/"\n'
        f"{code_exec}"
        f"{use}"
        "    schedule:\n"
        '      interval: "weekly"\n'
        "    open-pull-requests-limit: 0\n"
        "    groups:\n"
        f"      {stack}:\n"
        "        patterns:\n"
        '          - "*"\n'
    )


def readme(repo, stack, spec, issue_url, registry=None):
    via = f"Packages resolve from `{registry}`.\n" if registry else ""
    return (f"# {repo}\n\nGenerated by [{issue_url}]({issue_url}) for the `{stack}` stack.\n\n"
            f"Pins `{spec}` in `{STACKS[stack]['file']}` on purpose (a known-vulnerable version) "
            f"so Dependabot raises an alert and opens a security update PR.\n{via}")


LOCK_COMMANDS = {
    "node": (["npm", "install", "--package-lock-only", "--ignore-scripts", "--no-audit", "--no-fund"],
             ["package-lock.json"]),
    "ruby": (["bundle", "lock"], ["Gemfile.lock"]),
    "go": (None, ["go.mod", "go.sum"]),
}


def lockfiles(stack, files, spec, timeout=300, registry=None):
    """Best-effort lockfile generation. Returns {path: text} to add/overwrite, or {} if it fails.

    Dependabot security updates for bundler and gomod need a lockfile (`Gemfile.lock`,
    `go.sum`); npm gets one too so the resolved tree is pinned. Python needs none.
    """
    if stack not in LOCK_COMMANDS:
        return {}
    cmd, outputs = LOCK_COMMANDS[stack]
    with tempfile.TemporaryDirectory() as tmp:
        root = pathlib.Path(tmp)
        for path, text in files.items():
            (root / path).parent.mkdir(parents=True, exist_ok=True)
            (root / path).write_text(text)
        if stack == "go":
            cmd = ["go", "get", "@".join(split_spec(spec))]
        try:
            subprocess.run(cmd, cwd=root, check=True, capture_output=True, timeout=timeout,
                           env={**os.environ, "GOFLAGS": "-mod=mod", **({"GOPROXY": registry} if registry else {})})
        except (subprocess.CalledProcessError, subprocess.TimeoutExpired, FileNotFoundError):
            return {}
        out = {p: (root / p).read_text() for p in outputs if (root / p).is_file()}
        if stack == "go" and "go.sum" not in out:
            return {}
        return out

